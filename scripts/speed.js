// Things that make the app open faster. Used by postbuild.js.
//   1. Font preloading: the fonts needed to start are requested at the same time as the app's code,
//      instead of waiting until the code has arrived and run.
//   2. A service worker: keeps the app on the phone, so repeat opens download nothing (and the app
//      opens even with no connection). The page itself is always re-checked online first, so updates
//      still arrive on the next open.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

const urlOf = (BASE, dist, file) => BASE + "/" + path.relative(dist, file).split(path.sep).join("/");

// Where each font's files ended up (their names carry a content hash, so they change when a font does).
function fontMap(BASE, dist) {
  const files = walk(path.join(dist, "assets")).filter((f) => f.endsWith(".ttf"));
  const find = (prefix) => {
    const f = files.find((x) => path.basename(x).startsWith(prefix + "."));
    if (!f) throw new Error("speed: missing font file " + prefix);
    return urlOf(BASE, dist, f);
  };
  return {
    lora: [find("Lora_400Regular"), find("Lora_600SemiBold")],
    caveat: [find("Caveat_400Regular"), find("Caveat_700Bold")],
    patrick: [find("PatrickHand_400Regular")],
    elite: [find("SpecialElite_400Regular")],
    cormorant: [find("CormorantGaramond_500Medium"), find("CormorantGaramond_700Bold")],
    hebrew: [find("FrankRuhlLibre_400Regular"), find("FrankRuhlLibre_700Bold")],
  };
}

// Runs at the top of the page: reads which font you chose (the app keeps it in localStorage) and starts
// downloading the interface font plus that one right away. Anything that goes wrong is ignored.
function preloadScript(map) {
  return `<script>(function(){try{var M=${JSON.stringify(map)};var s=JSON.parse(localStorage.getItem("logbook.settings.v1")||"{}");var k=M[s.font]?s.font:"patrick";var he=s.language==="he";if(he){document.documentElement.dir="rtl";document.documentElement.lang="he"}var list=M.lora.concat(k==="lora"?[]:M[k],he?M.hebrew:[]);list.forEach(function(u){var l=document.createElement("link");l.rel="preload";l.as="font";l.type="font/ttf";l.crossOrigin="anonymous";l.href=u;document.head.appendChild(l)})}catch(e){}})()</script>`;
}

const registerScript = (BASE) =>
  `<script>if("serviceWorker"in navigator){addEventListener("load",function(){navigator.serviceWorker.register("${BASE}/sw.js",{scope:"${BASE}/"}).catch(function(){})})}</script>`;

function writeServiceWorker(BASE, dist, map, jsUrl) {
  // The cache name changes whenever anything in the build changes, so old copies are cleaned up.
  const hash = crypto.createHash("sha1");
  for (const f of walk(dist).sort()) {
    if (path.basename(f) === "sw.js") continue;
    hash.update(path.relative(dist, f));
    hash.update(fs.readFileSync(f));
  }
  const version = hash.digest("hex").slice(0, 12);
  // What is saved straight away: the page, the code, and the fonts needed to start (default font included).
  const precache = [`${BASE}/`, jsUrl, `${BASE}/manifest.webmanifest`, ...map.lora, ...map.patrick];

  const code = `// Generated by scripts/speed.js. Keeps the app on the phone for fast repeat opens and offline use.
const CACHE = "rolodex-${version}";
const BASE = "${BASE}";
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      // the page is always fetched fresh; the other files have a content hash in their name, so a saved copy is always right
      .then((cache) => cache.addAll(PRECACHE.map((u) => (u === BASE + "/" ? new Request(u, { cache: "reload" }) : u))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("rolodex-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== location.origin || !url.pathname.startsWith(BASE + "/")) return;
  if (url.pathname === BASE + "/sw.js") return;
  event.respondWith(request.mode === "navigate" ? openPage() : savedFirst(request));
});

// The page: ask the network first so updates arrive at once, but give up after 4 seconds (or offline)
// and use the saved copy.
async function openPage() {
  const cache = await caches.open(CACHE);
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 4000);
    const response = await fetch(BASE + "/", { cache: "no-cache", signal: controller.signal });
    clearTimeout(timer);
    if (response.ok) cache.put(BASE + "/", response.clone());
    return response;
  } catch (e) {
    return (await cache.match(BASE + "/")) || Response.error();
  }
}

// Code, fonts and icons: use the saved copy if there is one, otherwise fetch it and save it.
async function savedFirst(request) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok && response.type === "basic") cache.put(request, response.clone());
  return response;
}
`;
  fs.writeFileSync(path.join(dist, "sw.js"), code);
  return { version, precache };
}

module.exports = { fontMap, preloadScript, registerScript, writeServiceWorker };
